import Foundation
import Testing
@testable import DustlingCore

@Suite struct AppScoutTests {
    private func scout(_ sandbox: TestSandbox) -> AppScout {
        AppScout(environment: sandbox.environment, sizer: DirectorySizer())
    }

    @Test func discoversNestedApps() throws {
        let sandbox = try TestSandbox()
        try sandbox.app("Applications/TI Connect/TI Data Editor.app", bundleID: "com.ti.editor")
        let apps = scout(sandbox).discover()
        #expect(apps.map(\.displayName) == ["TI Data Editor"])
        #expect(apps.first?.bundleID == "com.ti.editor")
        #expect(apps.first?.executableName == "App")
        #expect((apps.first?.bytes ?? 0) > 0)
        #expect(apps.first?.teamID == nil)
    }

    @Test func canSkipMeasuringSizes() throws {
        let sandbox = try TestSandbox()
        try sandbox.app("Applications/X.app", bundleID: "com.x")
        let apps = AppScout(environment: sandbox.environment, measuresSizes: false).discover()
        #expect(apps.map(\.bundleID) == ["com.x"])
        #expect(apps.first?.bytes == 0)
    }

    @Test func doesNotDescendIntoBundles() throws {
        let sandbox = try TestSandbox()
        try sandbox.app("Applications/X.app", bundleID: "com.x")
        try sandbox.app("Applications/X.app/Contents/Helpers/Helper.app", bundleID: "com.x.helper")
        let apps = scout(sandbox).discover()
        #expect(apps.map(\.displayName) == ["X"])
    }

    @Test func discoversSteamWrapperWithoutBundleID() throws {
        let sandbox = try TestSandbox()
        try sandbox.app(
            "home/Applications/Portal.app", bundleID: nil, executable: "run.sh",
            script: "#!/bin/bash\n# autogenerated file - do not edit\nopen steam://run/400\n")
        let apps = scout(sandbox).discover()
        let portal = try #require(apps.first)
        #expect(portal.displayName == "Portal")
        #expect(portal.bundleID == nil)
        #expect(portal.steamAppID == "400")
        #expect(portal.executableName == "run.sh")
    }

    @Test func binaryExecutableHasNoSteamID() throws {
        let sandbox = try TestSandbox()
        let url = try sandbox.app("Applications/Bin.app", bundleID: "com.bin")
        try Data([0xCF, 0xFA, 0xED, 0xFE, 0xFF, 0x00, 0x80]).write(
            to: url.appending(path: "Contents/MacOS/App"))
        #expect(scout(sandbox).discover().first?.steamAppID == nil)
    }

    @Test func namePriority() throws {
        let sandbox = try TestSandbox()
        try sandbox.app("Applications/A-file.app", bundleID: "a", displayName: "Display", bundleName: "Bundle")
        try sandbox.app("Applications/B-file.app", bundleID: "b", bundleName: "Bundle B")
        try sandbox.app("Applications/c-file.app", bundleID: "c")
        let names = scout(sandbox).discover().map(\.displayName)
        #expect(names == ["Bundle B", "c-file", "Display"])
    }

    @Test func sortedCaseInsensitively() throws {
        let sandbox = try TestSandbox()
        try sandbox.app("Applications/zeta.app", bundleID: "z")
        try sandbox.app("Applications/Alpha.app", bundleID: "a")
        try sandbox.app("Applications/beta.app", bundleID: "b")
        #expect(scout(sandbox).discover().map(\.displayName) == ["Alpha", "beta", "zeta"])
    }

    @Test func listsSymlinkedAppByOwnPathButSkipsSystemAliases() throws {
        let sandbox = try TestSandbox()
        let real = try sandbox.app("elsewhere/Real.app", bundleID: "real")
        let fm = FileManager.default
        let link = sandbox.environment.applicationDirectories[0].appending(path: "Linked.app")
        try fm.createSymbolicLink(at: link, withDestinationURL: real)
        let sys = sandbox.environment.applicationDirectories[0].appending(path: "SysAlias.app")
        try fm.createSymbolicLink(at: sys, withDestinationURL: URL(filePath: "/System/Applications/Calculator.app"))
        let apps = scout(sandbox).discover()
        #expect(apps.map(\.displayName) == ["Linked"])
        #expect(apps.first?.url.lastPathComponent == "Linked.app")
    }

    @Test func doesNotFollowSymlinkedDirectories() throws {
        let sandbox = try TestSandbox()
        try sandbox.app("outside/Hidden.app", bundleID: "hidden")
        let fm = FileManager.default
        let dir = sandbox.environment.applicationDirectories[0]
        try fm.createSymbolicLink(at: dir.appending(path: "Loop"), withDestinationURL: sandbox.root.appending(path: "outside"))
        try fm.createSymbolicLink(at: dir.appending(path: "Cycle"), withDestinationURL: dir)
        #expect(scout(sandbox).discover().isEmpty)
    }

    @Test func respectsDepthLimit() throws {
        let sandbox = try TestSandbox()
        try sandbox.app("Applications/a/b/Ok.app", bundleID: "ok")       // depth 3
        try sandbox.app("Applications/a/b/c/TooDeep.app", bundleID: "deep") // depth 4
        #expect(scout(sandbox).discover().map(\.displayName) == ["Ok"])
    }

    @Test func reportsUnreadableDirectories() throws {
        let sandbox = try TestSandbox()
        try sandbox.app("Applications/Fine.app", bundleID: "fine")
        let locked = try sandbox.directory("Applications/Locked")
        try FileManager.default.setAttributes([.posixPermissions: 0o000], ofItemAtPath: locked.path)
        defer { try? FileManager.default.setAttributes([.posixPermissions: 0o755], ofItemAtPath: locked.path) }
        let result = scout(sandbox).discoverWithIssues()
        #expect(result.apps.map(\.displayName) == ["Fine"])
        #expect(result.unreadable.map(\.lastPathComponent) == ["Locked"])
    }

    @Test func missingApplicationDirectoryIsNotReportedUnreadable() throws {
        let sandbox = try TestSandbox()
        try sandbox.app("Applications/Fine.app", bundleID: "fine")
        var env = sandbox.environment
        env.applicationDirectories.append(sandbox.root.appending(path: "NoSuchApplications"))
        let result = AppScout(environment: env, sizer: DirectorySizer()).discoverWithIssues()
        #expect(result.unreadable.isEmpty)
        #expect(result.apps.map(\.displayName) == ["Fine"])
    }
    // MARK: - Symlinked apps (Important #7)

    @Test func symlinkedAppReportsItsTargetAndTheTargetsSize() throws {
        let sandbox = try TestSandbox()
        let real = try sandbox.app("elsewhere/Riot Client.app", bundleID: "com.riot")
        try sandbox.file("elsewhere/Riot Client.app/Contents/Resources/big.bin", bytes: 64 * 1024)
        try sandbox.app("Applications/Plain.app", bundleID: "com.plain")
        let link = sandbox.environment.applicationDirectories[0].appending(path: "Riot İstemcisi.app")
        try FileManager.default.createSymbolicLink(at: link, withDestinationURL: real)
        let apps = scout(sandbox).discover()
        let riot = try #require(apps.first { $0.bundleID == "com.riot" })
        #expect(riot.url.lastPathComponent == "Riot İstemcisi.app")
        #expect(riot.linkTarget?.resolvingSymlinksInPath().path == real.resolvingSymlinksInPath().path)
        #expect(riot.bytes == DirectorySizer().measure(real).bytes)
        #expect(riot.bytes >= 64 * 1024)
        let plain = try #require(apps.first { $0.bundleID == "com.plain" })
        #expect(plain.linkTarget == nil)
        #expect(plain.bytes == DirectorySizer().measure(plain.url).bytes)
    }
}

